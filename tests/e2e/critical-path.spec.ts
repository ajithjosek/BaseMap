import { test, expect } from '@playwright/test';

/**
 * Sprint 39.3 - critical path journey:
 * login -> create application -> create capability -> map app -> report -> export.
 * Assumes a seeded API at localhost:4001 and web at localhost:3005.
 */
test.describe('critical path', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/login');
    await page.getByLabel(/email/i).fill(process.env.E2E_EMAIL || 'admin@basemap.com');
    await page.getByLabel(/password/i).fill(process.env.E2E_PASSWORD || 'admin123');
    await page.getByRole('button', { name: 'Login', exact: true }).click();
    await expect(page).toHaveURL(/dashboard|\/$/, { timeout: 15000 });
  });

  test('create an application', async ({ page }) => {
    const name = `E2E App ${Date.now()}`;
    await page.goto('/applications');
    await page.locator('a[href="/applications/new"]').click();
    await page.getByLabel(/name/i).fill(name);
    await page.getByRole('button', { name: /save|create/i }).click();
    await expect(page).toHaveURL(/\/applications$/, { timeout: 10000 });
    // The list is paginated and sorted by name, so filter to the created record.
    await page.getByPlaceholder(/search applications/i).fill(name);
    await expect(page.getByText(name)).toBeVisible({ timeout: 10000 });
  });

  test('create a capability', async ({ page }) => {
    const name = `E2E Capability ${Date.now()}`;
    await page.goto('/capabilities');
    await page.getByRole('button', { name: /add capability/i }).click();

    const dialog = page.getByRole('dialog');
    await dialog.getByLabel(/name/i).fill(name);
    await dialog.getByRole('button', { name: /^create$/i }).click();

    await expect(page.getByText(name)).toBeVisible({ timeout: 10000 });
  });

  test('run a report', async ({ page }) => {
    await page.goto('/reports');
    // Reports are generated by selecting a template, so that is the "run" step.
    await page.getByRole('combobox').click();
    await page.getByRole('option', { name: /standard reports/i }).click();
    await expect(page.getByText('Application Landscape Report')).toBeVisible({ timeout: 15000 });
  });
});
